#!/usr/bin/env python3
"""Turn the Terraform `ansible_inventory` output into an Ansible YAML inventory.

Usage (you run this after a successful apply; it only reads Terraform's state):

    cd terraform/environments/staging
    terraform output -json ansible_inventory | ../../../scripts/tf-to-inventory.py

    # or from a saved file, writing somewhere else:
    scripts/tf-to-inventory.py --input out.json --output /tmp/hosts.yml

Accepts either `terraform output -json ansible_inventory` (the bare value) or
`terraform output -json` (an object holding an "ansible_inventory" key).
Standard library only. The generated file is git-ignored and contains no secrets.
"""
from __future__ import annotations

import argparse
import ipaddress
import json
import re
import sys
from pathlib import Path

NAME_RE = re.compile(r"^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$")
GROUP_RE = re.compile(r"^[a-z][a-z0-9_]*$")
USER_RE = re.compile(r"^[a-z_][a-z0-9_-]{0,31}$")

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = REPO_ROOT / "ansible" / "inventory" / "staging" / "hosts.yml"


def fail(message: str) -> "None":
    sys.exit(f"ERROR: {message}")


def load(raw: str) -> dict:
    try:
        data = json.loads(raw)
    except json.JSONDecodeError as exc:
        fail(f"input is not valid JSON: {exc}")
    if isinstance(data, dict) and "ansible_inventory" in data:
        data = data["ansible_inventory"]
        if isinstance(data, dict) and "value" in data:
            data = data["value"]
    if not isinstance(data, dict) or "hosts" not in data:
        fail("expected an object with 'hosts' (and optional 'groups').")
    return data


def validate(data: dict) -> tuple[dict, dict]:
    hosts = data.get("hosts") or {}
    groups = data.get("groups") or {}
    if not isinstance(hosts, dict) or not isinstance(groups, dict):
        fail("'hosts' and 'groups' must be objects.")
    for name, attrs in hosts.items():
        if not NAME_RE.match(name):
            fail(f"invalid host name: {name!r}")
        for key in ("ansible_host", "ansible_user", "vm_id"):
            if key not in attrs:
                fail(f"host {name}: missing '{key}'")
        try:
            ipaddress.IPv4Address(attrs["ansible_host"])
        except ValueError:
            fail(f"host {name}: ansible_host is not an IPv4 address")
        if not USER_RE.match(str(attrs["ansible_user"])):
            fail(f"host {name}: invalid ansible_user")
        if not isinstance(attrs["vm_id"], int) or isinstance(attrs["vm_id"], bool):
            fail(f"host {name}: vm_id must be an integer")
    for group, members in groups.items():
        if not GROUP_RE.match(group):
            fail(f"invalid group name: {group!r}")
        unknown = [m for m in members if m not in hosts]
        if unknown:
            fail(f"group {group}: unknown hosts {unknown}")
    return hosts, groups


def q(value: object) -> str:
    """JSON scalars are valid YAML scalars; this quotes strings safely."""
    return json.dumps(value)


def render(hosts: dict, groups: dict) -> str:
    grouped = {m for members in groups.values() for m in members}
    lines = [
        "---",
        "# GENERATED by scripts/tf-to-inventory.py from `terraform output`. Do not edit; do not commit.",
        "all:",
        "  children:",
        "    lab:",
    ]

    def host_block(name: str, indent: str) -> list[str]:
        h = hosts[name]
        return [
            f"{indent}{name}:",
            f"{indent}  ansible_host: {q(h['ansible_host'])}",
            f"{indent}  ansible_user: {q(h['ansible_user'])}",
            f"{indent}  vm_id: {h['vm_id']}",
        ]

    ungrouped = sorted(set(hosts) - grouped)
    if ungrouped:
        lines.append("      hosts:")
        for name in ungrouped:
            lines += host_block(name, "        ")
    if groups:
        lines.append("      children:")
        for group in sorted(groups):
            members = sorted(groups[group])
            if not members:
                lines.append(f"        {group}: {{}}")
                continue
            lines += [f"        {group}:", "          hosts:"]
            for name in members:
                lines += host_block(name, "            ")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--input", "-i", default="-", help="JSON file, or - for stdin (default)")
    parser.add_argument("--output", "-o", default=str(DEFAULT_OUTPUT), help="output path, or - for stdout")
    args = parser.parse_args()

    raw = sys.stdin.read() if args.input == "-" else Path(args.input).read_text(encoding="utf-8")
    hosts, groups = validate(load(raw))
    text = render(hosts, groups)

    if args.output == "-":
        sys.stdout.write(text)
        return
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"Wrote {out} ({len(hosts)} host(s)).", file=sys.stderr)


if __name__ == "__main__":
    main()
